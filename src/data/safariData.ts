export const CURRENCIES: Record<string, CurrencyConfig> = {
  USD: { code: 'USD', symbol: '$', name: 'US Dollar', rateAgainstUSD: 1 },
  EUR: { code: 'EUR', symbol: '€', name: 'Euro', rateAgainstUSD: 0.92 },
  GBP: { code: 'GBP', symbol: '£', name: 'British Pound', rateAgainstUSD: 0.78 },
  KES: { code: 'KES', symbol: 'KSh ', name: 'Kenyan Shilling', rateAgainstUSD: 129.50 },
};

export function formatPrice(usdAmount: number, currencyCode: string): string {
  const currency = CURRENCIES[currencyCode] || CURRENCIES.USD;
  const converted = Math.round(usdAmount * currency.rateAgainstUSD);

  if (currencyCode === 'KES') {
    return `${currency.symbol}${converted.toLocaleString('en-KE')}`;
  }
  return `${currency.symbol}${converted.toLocaleString('en-US')}`;
}

