export function getWhatsAppBookingUrl(details: {
  safariTitle: string;
  tier?: string;
  durationDays?: number;
  travelDate?: string;
  guests?: number;
  totalPrice?: string;
  customerName?: string;
  customerPhone?: string;
  bookingRef?: string;
}): string {
  const phone = TRUST_CREDENTIALS.whatsappRaw;
  const lines = [
    `Jambo Mountain Peak Adventures!`,
    details.bookingRef ? `*Booking Reference: ${details.bookingRef}*` : `*New Safari Booking Request*`,
    `--------------------------`,
    `• Safari: ${details.safariTitle}`,
    details.tier ? `• Accommodation Tier: ${details.tier.toUpperCase()}` : null,
    details.durationDays ? `• Duration: ${details.durationDays} Days` : null,
    details.travelDate ? `• Travel Date: ${details.travelDate}` : null,
    details.guests ? `• Travelers: ${details.guests}` : null,
    details.totalPrice ? `• Total / Deposit: ${details.totalPrice}` : null,
    details.customerName ? `• Client Name: ${details.customerName}` : null,
    details.customerPhone ? `• Phone: ${details.customerPhone}` : null,
    `--------------------------`,
    details.bookingRef
      ? `I have placed this booking on your website. Please connect with me to confirm my reservation and itinerary pack!`
      : `I would like to book this safari with you. Please confirm availability and send payment / reservation details. Asante!`,
  ].filter(Boolean);

  const text = encodeURIComponent(lines.join('\n'));
  return `https://wa.me/${phone}?text=${text}`;
}


